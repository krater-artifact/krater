// Trace input: a Twitter cache trace in its text format, or the compact binary record format below (what replay --bin
// reads and ycsb_gen writes), so that a full trace is parsed once and can feed several processes.
//
// Binary record (one little-endian u64 per valid text line, same order):
//   bits  0..31  key id (first appearance in the text trace, 1-based: indexes the trace's objsize.bin)
//   bits 32..34  op (opmap below: 1 write, 2 GET, 3 incr/decr, 4 delete)
//   bits 35..42  top 8 bits of KeyTab::hash(client id): host = hash * N >> 64 needs only these for N = 2^k <= 256
//   bits 43..63  timestamp in s (< 2^21)
// The random-routing stream (splitmix64 from the seed, one draw per record) is regenerated by the reader, so random and
// client routing are bit-identical to the text path for N a power of two. <bin>.meta (text, "name value" per line) holds
// the converter's counts (lines, bad_lines, records, distinct_keys, clients, ...).
#pragma once
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <string_view>
#include <unistd.h>
#include <vector>

struct LineReader {
  int fd; std::vector<char> buf; size_t beg = 0, end = 0; bool eof = false;
  explicit LineReader(int f) : fd(f), buf(64u << 20) {}
  bool next(std::string_view &line) {
    for (;;) {
      char *p = (char *)memchr(buf.data() + beg, '\n', end - beg);
      if (p) { line = std::string_view(buf.data() + beg, p - (buf.data() + beg)); beg = p - buf.data() + 1; return true; }
      if (eof) { if (beg < end) { line = std::string_view(buf.data() + beg, end - beg); beg = end; return true; } return false; }
      memmove(buf.data(), buf.data() + beg, end - beg); end -= beg; beg = 0;
      if (end == buf.size()) buf.resize(buf.size() * 2);
      ssize_t r = read(fd, buf.data() + end, buf.size() - end);
      if (r < 0) { perror("read"); exit(1); }
      if (r == 0) eof = true; else end += r;
    }
  }
};

struct KeyTab {
  struct Slot { uint64_t h; uint64_t off; uint32_t len; uint32_t id; };
  std::vector<Slot> t; std::vector<char> arena; uint64_t mask, n = 0;
  KeyTab() : t(1u << 24), mask((1u << 24) - 1) { arena.reserve(1u << 30); }
  static uint64_t hash(std::string_view s) {
    uint64_t h = 0xcbf29ce484222325ull;
    for (unsigned char c : s) { h ^= c; h *= 0x100000001b3ull; }
    h ^= h >> 33; h *= 0xFF51AFD7ED558CCDull; h ^= h >> 33;
    return h | 1;
  }
  void grow() {
    std::vector<Slot> old; old.swap(t);
    t.assign(old.size() * 2, Slot{0, 0, 0, 0}); mask = t.size() - 1;
    for (auto &s : old) if (s.h) { uint64_t i = s.h & mask; while (t[i].h) i = (i + 1) & mask; t[i] = s; }
  }
  uint32_t get(std::string_view k, bool *isnew) {
    uint64_t h = hash(k), i = h & mask;
    for (;;) {
      Slot &s = t[i];
      if (!s.h) break;
      if (s.h == h && s.len == k.size() && memcmp(arena.data() + s.off, k.data(), k.size()) == 0) { *isnew = false; return s.id; }
      i = (i + 1) & mask;
    }
    *isnew = true;
    uint64_t off = arena.size();
    arena.insert(arena.end(), k.begin(), k.end());
    t[i] = Slot{h, off, (uint32_t)k.size(), (uint32_t)++n};
    if (n * 2 > t.size()) grow();
    return (uint32_t)n;
  }
};

inline int opmap(std::string_view op) {
  if (op == "get" || op == "gets") return 2;
  if (op == "set" || op == "add" || op == "replace" || op == "cas" || op == "append" || op == "prepend") return 1;
  if (op == "incr" || op == "decr" || op == "update") return 3;
  if (op == "delete") return 4;
  return 2;
}

static inline uint64_t splitmix(uint64_t &s) {  // splitmix64
  s += 0x9E3779B97F4A7C15ull;
  uint64_t z = s;
  z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull;
  z = (z ^ (z >> 27)) * 0x94D049BB133111EBull;
  return z ^ (z >> 31);
}

// One text line -> (key, client hash, op, timestamp); false for a malformed line.
struct Parsed { std::string_view key, client, op; uint32_t ts; };
static inline bool parse_line(std::string_view line, Parsed &p) {
  size_t cpos[5]; int nc = 0; size_t pos = line.size();
  while (nc < 5) { if (pos == 0) break; size_t q = line.rfind(',', pos - 1); if (q == std::string_view::npos) break; cpos[nc++] = q; pos = q; }
  size_t c0 = line.find(',');
  if (nc < 5 || c0 == std::string_view::npos || c0 >= cpos[4]) return false;
  p.key = line.substr(c0 + 1, cpos[4] - c0 - 1);
  p.client = line.substr(cpos[2] + 1, cpos[1] - cpos[2] - 1);
  p.op = line.substr(cpos[1] + 1, cpos[0] - cpos[1] - 1);
  p.ts = (uint32_t)strtoull(line.data(), nullptr, 10);
  return true;
}

static inline uint64_t pack_rec(uint32_t key, int op, uint64_t client_hash, uint32_t ts) {
  return (uint64_t)key | (uint64_t)(op & 7) << 32 | (client_hash >> 56) << 35 | (uint64_t)ts << 43;
}
static inline uint32_t rec_key(uint64_t r) { return (uint32_t)r; }
static inline uint8_t rec_op(uint64_t r) { return (uint8_t)(r >> 32 & 7); }
static inline uint64_t rec_client(uint64_t r) { return (r >> 35 & 0xff) << 56; }  // valid for host = x * N >> 64, N = 2^k <= 256
static inline uint32_t rec_ts(uint64_t r) { return (uint32_t)(r >> 43); }
static const uint32_t REC_TS_MAX = (1u << 21) - 1;

struct BinReader {
  FILE *f; std::vector<uint64_t> buf;
  explicit BinReader(const char *path) : f(fopen(path, "rb")) { if (!f) { perror(path); exit(1); } }
  ~BinReader() { if (f) fclose(f); }
  size_t read(size_t n) {  // up to n records into buf
    buf.resize(n);
    size_t got = fread(buf.data(), 8, n, f);
    if (got < n && ferror(f)) { perror("fread records"); exit(1); }
    buf.resize(got);
    return got;
  }
};

// <bin>.meta value by name (empty if missing)
inline std::string meta_get(const std::string &bin, const char *name) {
  FILE *f = fopen((bin + ".meta").c_str(), "r");
  if (!f) return "";
  char k[256], v[256]; std::string out;
  while (fscanf(f, "%255s %255s", k, v) == 2) if (!strcmp(k, name)) { out = v; break; }
  fclose(f);
  return out;
}

inline std::vector<int> parse_list(const std::string &s) {
  std::vector<int> v;
  for (size_t p = 0; p < s.size();) { size_t q = s.find(',', p); if (q == std::string::npos) q = s.size(); v.push_back(atoi(s.substr(p, q - p).c_str())); p = q + 1; }
  return v;
}

// Cache fractions in percent, "1,1.5,10" -> basis points (1/100 of a percent): M = total * bp / 10000, which equals the
// old integer-percent M = total * pct / 100 exactly.
inline std::vector<int> parse_bp_list(const std::string &s) {
  std::vector<int> v;
  for (size_t p = 0; p < s.size();) { size_t q = s.find(',', p); if (q == std::string::npos) q = s.size(); v.push_back((int)(atof(s.substr(p, q - p).c_str()) * 100 + 0.5)); p = q + 1; }
  return v;
}
// M_frac as printed: "%.2f" for whole percents (byte-identical to the archived CSVs), "%.4f" otherwise
inline void fmt_frac(char *buf, size_t n, int bp) { snprintf(buf, n, bp % 100 == 0 ? "%.2f" : "%.4f", bp / 10000.0); }

// Leading --name=value options, removed from argv; returns the value of --name or def.
struct Opts {
  std::vector<std::pair<std::string, std::string>> kv;
  Opts(int &argc, char **argv) {
    int j = 1;
    for (int i = 1; i < argc; i++) {
      if (!strncmp(argv[i], "--", 2)) { std::string a = argv[i] + 2; size_t e = a.find('=');
        kv.emplace_back(a.substr(0, e), e == std::string::npos ? "1" : a.substr(e + 1)); }
      else argv[j++] = argv[i];
    }
    argc = j;
  }
  std::string get(const char *name, const char *def = "") const { for (auto &p : kv) if (p.first == name) return p.second; return def; }
};
